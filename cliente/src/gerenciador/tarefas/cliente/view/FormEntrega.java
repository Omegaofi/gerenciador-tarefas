    private void estilizar() {
        getRootPane().setDefaultButton(btnSalvar);
        lblTitulo.setFont(Tema.fonte(Font.BOLD, 18));
        Tema.subtitulo(lblSubtitulo);
        lblAlerta.setFont(Tema.fonte(Font.BOLD, 12));
        Tema.rotuloCampo(lblCampoDescricao);
        Tema.rotuloCampo(lblCampoLink);
        Tema.estilizarCampo(txtDescricao);
        Tema.estilizarCampo(txtLink);
        Tema.subtitulo(lblDica);
        Tema.secundario(btnCancelar).addActionListener(e -> dispose());
        Tema.primario(btnSalvar).addActionListener(e -> salvar());
    }

    private static String subtitulo(Tarefa tarefa) {
        String prazo = tarefa.getPrazo() != null ? new SimpleDateFormat("dd/MM/yyyy").format(tarefa.getPrazo()) : "sem prazo";
        String projeto = tarefa.getProjeto() != null ? tarefa.getProjeto().getTitulo() : "";
        return tarefa.getTitulo() + " · " + projeto + " · prazo " + prazo;
    }

    private void salvar() {
        String descricao = txtDescricao.getText().trim();
        String link = txtLink.getText().trim();
        if (descricao.isEmpty()) {
            lblAlerta.setText("Descreva a entrega.");
            txtDescricao.requestFocus();
            return;
        }
        if (!link.matches("(?i)^https?://\\S+$")) {
            lblAlerta.setText("Informe um link válido, começando com http:// ou https://");
            txtLink.requestFocus();
            return;
        }

        Usuario logado = GerenciadorTarefasCliente.conexaoCliente.getUsuarioLogado();
        Arquivo arquivo = new Arquivo(descricao, link, logado, tarefa);
        EntregaTarefa entrega = new EntregaTarefa(new Date(), "enviada", tarefa, arquivo);
        if (GerenciadorTarefasCliente.conexaoCliente.entregaTarefaEnviar(entrega)) {
            JOptionPane.showMessageDialog(this, "Entrega enviada! O criador do projeto vai revisar.");
            dispose();
            if (aoEnviar != null) {
                aoEnviar.run();
            }
        } else {
            lblAlerta.setText("Erro ao enviar a entrega. Tente novamente.");
        }
    }

