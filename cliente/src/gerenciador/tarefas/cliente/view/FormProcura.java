    private void prepararFiltros() {
        Tema.estilizarCombo(comboArea);
        comboArea.setPreferredSize(new Dimension(230, 38));
        comboArea.addItem(TODAS_AREAS);

        // 10px entre os itens da barra de filtros (igual à barra de ações das outras telas)
        java.awt.Component[] itens = painelFiltros.getComponents();
        painelFiltros.removeAll();
        for (int i = 0; i < itens.length; i++) {
            if (i > 0) {
                painelFiltros.add(Box.createHorizontalStrut(10));
            }
            painelFiltros.add(itens[i]);
        }

        // A busca filtra enquanto digita
        inputBusca.getDocument().addDocumentListener(new DocumentListener() {
            @Override
            public void insertUpdate(DocumentEvent e) {
                mostrarCards();
            }

            @Override
            public void removeUpdate(DocumentEvent e) {
                mostrarCards();
            }

            @Override
            public void changedUpdate(DocumentEvent e) {
                mostrarCards();
            }
        });
        scrollProjetos.getViewport().setOpaque(false);
        scrollProjetos.getVerticalScrollBar().setUnitIncrement(16);
        scrollProjetos.getVerticalScrollBar().setPreferredSize(new Dimension(8, 0));
        scrollProjetos.getVerticalScrollBar().setUI(new javax.swing.plaf.basic.BasicScrollBarUI() {
            @Override
            protected void configureScrollBarColors() {
                thumbColor = Tema.BORDA;
                trackColor = Tema.FUNDO;
            }

            @Override
            protected javax.swing.JButton createDecreaseButton(int orientacao) {
                return botaoInvisivel();
            }

            @Override
            protected javax.swing.JButton createIncreaseButton(int orientacao) {
                return botaoInvisivel();
            }

            private javax.swing.JButton botaoInvisivel() {
                javax.swing.JButton b = new javax.swing.JButton();
                b.setPreferredSize(new Dimension(0, 0));
                return b;
            }
        });
    }

    /** Busca no servidor os projetos disponíveis e monta a tela de novo. */
    private void carregar() {
        disponiveis = conexao.inscricaoProjetosDisponiveis();

        boolean semProjeto = !conexao.isCriador() && !conexao.usuarioParticipaDeProjeto();
        lblSubtitulo.setText(semProjeto
                ? "Você ainda não participa de nenhum projeto. Escolha um abaixo e peça para entrar."
                : "Encontre novos projetos e peça para participar.");

        // Áreas que existem nos projetos disponíveis, em ordem alfabética
        Object areaEscolhida = comboArea.getSelectedItem();
        TreeSet<String> areas = new TreeSet<>(String.CASE_INSENSITIVE_ORDER);
        for (Inscricao i : disponiveis) {
            String area = i.getProjeto().getAreaAtuacao();
            if (area != null && !area.isBlank()) {
                areas.add(area.trim());
            }
        }
        preenchendoCombo = true;
        comboArea.removeAllItems();
        comboArea.addItem(TODAS_AREAS);
        for (String area : areas) {
            comboArea.addItem(area);
        }
        comboArea.setSelectedItem(areas.contains(String.valueOf(areaEscolhida)) ? areaEscolhida : TODAS_AREAS);
        preenchendoCombo = false;

        mostrarCards();
    }

    /** Aplica busca + área sobre a lista já carregada e desenha os cards. */
    private void mostrarCards() {
        String busca = normalizar(inputBusca.getText());
        String area = (String) comboArea.getSelectedItem();
        boolean todasAreas = area == null || TODAS_AREAS.equals(area);

        ArrayList<Inscricao> visiveis = new ArrayList<>();
        for (Inscricao i : disponiveis) {
            Projeto p = i.getProjeto();
            boolean areaOk = todasAreas || area.equalsIgnoreCase(p.getAreaAtuacao() == null ? "" : p.getAreaAtuacao().trim());
            String texto = normalizar(p.getTitulo() + " " + p.getDescricao());
            if (areaOk && (busca.isEmpty() || texto.contains(busca))) {
                visiveis.add(i);
            }
        }

        int total = visiveis.size();
        lblResultado.setText(total == 0 ? "Nenhum projeto encontrado"
                : total + (total == 1 ? " projeto disponível" : " projetos disponíveis"));

        painelProjetos.removeAll();
        if (total == 0) {
            painelProjetos.add(cardVazio(disponiveis.isEmpty()), BorderLayout.NORTH);
        } else {
            JPanel grade = new JPanel(new GridLayout(0, 2, 14, 14));
            grade.setOpaque(false);
            for (Inscricao i : visiveis) {
                grade.add(cardProjeto(i));
            }
            painelProjetos.add(grade, BorderLayout.NORTH);
        }
        painelProjetos.revalidate();
        painelProjetos.repaint();
    }

    /** Minúsculas e sem acento, para "Inteligência" achar "inteligencia". */
    private static String normalizar(String texto) {
        if (texto == null) {
            return "";
        }
        return Normalizer.normalize(texto, Normalizer.Form.NFD).replaceAll("\\p{M}", "").toLowerCase().trim();
    }

