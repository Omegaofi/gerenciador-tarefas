    private void estilizar() {
        PainelTela.estilizarMarca(lblLogo, lblChamada, lblCopyright,
                lblDestaque1, lblDestaque2, lblDestaque3, lblDestaque4);

        Tema.logo(lblLogoPequeno, 16, false);
        Tema.subtitulo(lblPlataforma);
        lblTitulo.setFont(Tema.fonte(Font.BOLD, 17));
        lblAlerta.setFont(Tema.fonte(Font.BOLD, 12));
        Tema.rotuloCampo(lblNome);
        Tema.rotuloCampo(lblEmail);
        Tema.rotuloCampo(lblSenha);
        Tema.rotuloCampo(lblConfirmar);
        Tema.rotuloCampo(lblTipo);
        Tema.estilizarCampo(txtNome);
        Tema.estilizarCampo(txtEmail);
        Tema.estilizarCampo(txtSenha);
        Tema.estilizarCampo(txtConfirmar);
        selecionarTipo("criador");
        btnCriador.addActionListener(e -> selecionarTipo("criador"));
        btnParticipante.addActionListener(e -> selecionarTipo("participante"));
        Tema.primario(btnCriar).addActionListener(e -> cadastrar());
        Tema.subtitulo(lblJaTemConta);
        Tema.link(lnkEntrar).addMouseListener(new MouseAdapter() {
            @Override
            public void mouseClicked(MouseEvent e) {
                voltarParaLogin("");
            }
        });
    }

    /** Alterna o botão escolhido entre Criador e Participante (o escolhido fica preto). */
    private void selecionarTipo(String tipo) {
        tipoSelecionado = tipo;
        if ("criador".equals(tipo)) {
            Tema.primario(btnCriador);
            Tema.secundario(btnParticipante);
        } else {
            Tema.secundario(btnCriador);
            Tema.primario(btnParticipante);
        }
    }

    private void cadastrar() {
        String nome = txtNome.getText().trim();
        String email = txtEmail.getText().trim();
        String senha = new String(txtSenha.getPassword());
        String confirmar = new String(txtConfirmar.getPassword());

        if (nome.isEmpty() || email.isEmpty() || senha.isEmpty()) {
            lblAlerta.setText("Preencha nome, e-mail e senha.");
            return;
        }
        if (!email.matches("^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$")) {
            lblAlerta.setText("Informe um e-mail válido.");
            txtEmail.requestFocus();
            return;
        }
        if (senha.length() < 6) {
            lblAlerta.setText("A senha precisa ter ao menos 6 caracteres.");
            txtSenha.requestFocus();
            return;
        }
        if (!senha.equals(confirmar)) {
            lblAlerta.setText("As senhas não conferem.");
            txtConfirmar.setText("");
            txtConfirmar.requestFocus();
            return;
        }

        Usuario novo = new Usuario(nome, email, senha, null, tipoSelecionado);
        if (GerenciadorTarefasCliente.conexaoCliente.usuarioInserir(novo)) {
            JOptionPane.showMessageDialog(this, "Conta criada com sucesso! Faça login para continuar.");
            voltarParaLogin(email);
        } else {
            lblAlerta.setText("Não foi possível criar a conta. Este e-mail já está em uso?");
        }
    }

    private void voltarParaLogin(String email) {
        TelaLogin telaLogin = new TelaLogin(email);
        telaLogin.setBounds(getBounds());
        telaLogin.setVisible(true);
        dispose();
    }

