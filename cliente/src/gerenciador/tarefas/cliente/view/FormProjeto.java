    private void estilizar() {
        getRootPane().setDefaultButton(btnSalvar);
        lblTitulo.setFont(Tema.fonte(Font.BOLD, 18));
        Tema.subtitulo(lblSubtitulo);
        lblAlerta.setFont(Tema.fonte(Font.BOLD, 12));
        Tema.rotuloCampo(lblCampoTitulo);
        Tema.rotuloCampo(lblCampoDescricao);
        Tema.rotuloCampo(lblCampoArea);
        Tema.rotuloCampo(lblCampoStatus);
        Tema.estilizarCampo(txtTitulo);
        Tema.estilizarCampo(txtDescricao);
        jScrollPane1.setBorder(null);
        Tema.secundario(btnCancelar).addActionListener(e -> dispose());
        Tema.primario(btnSalvar).addActionListener(e -> salvar());
    }

    private void salvar() {
        String titulo = txtTitulo.getText().trim();
        if (titulo.isEmpty()) {
            lblAlerta.setText("Informe o título do projeto.");
            txtTitulo.requestFocus();
            return;
        }
        Object areaSelecionada = cmbArea.getSelectedItem();
        String area = areaSelecionada != null ? areaSelecionada.toString().trim() : "";
        String status = ((Opcao) cmbStatus.getSelectedItem()).valor();
        Usuario logado = GerenciadorTarefasCliente.conexaoCliente.getUsuarioLogado();

        boolean ok;
        if (projeto != null) {
            Projeto projetoEditar = new Projeto(projeto.getId(), titulo, txtDescricao.getText().trim(),
                    area, status, logado, projeto.getCriadoEm());
            ok = GerenciadorTarefasCliente.conexaoCliente.projetoAtualizar(projetoEditar);
        } else {
            Projeto projetoInserir = new Projeto(titulo, txtDescricao.getText().trim(), area, status, logado);
            ok = GerenciadorTarefasCliente.conexaoCliente.projetoInserir(projetoInserir);
        }

        if (ok) {
            JOptionPane.showMessageDialog(this, projeto != null ? "Projeto atualizado com sucesso!" : "Projeto criado com sucesso!");
            dispose();
            if (aoSalvar != null) {
                aoSalvar.run();
            }
        } else {
            lblAlerta.setText("Erro ao salvar o projeto. Tente novamente.");
        }
    }

