    private void estilizar() {
        getRootPane().setDefaultButton(btnSalvar);
        lblTitulo.setFont(Tema.fonte(Font.BOLD, 18));
        Tema.subtitulo(lblSubtitulo);
        lblAlerta.setFont(Tema.fonte(Font.BOLD, 12));
        Tema.rotuloCampo(lblCampoTitulo);
        Tema.rotuloCampo(lblCampoProjeto);
        Tema.rotuloCampo(lblCampoResponsavel);
        Tema.rotuloCampo(lblCampoPrazo);
        Tema.rotuloCampo(lblCampoStatus);
        Tema.estilizarCampo(txtTitulo);
        Tema.secundario(btnCancelar).addActionListener(e -> dispose());
        Tema.primario(btnSalvar).addActionListener(e -> salvar());
    }

    private void carregarCombos() {
        Usuario logado = conexao.getUsuarioLogado();
        cmbProjeto.removeAllItems();
        for (Projeto projeto : conexao.projetoListaPorCriador(logado.getId())) {
            cmbProjeto.addItem(projeto);
        }
        cmbProjeto.setRenderer(renderer(Projeto::getTitulo));

        cmbResponsavel.removeAllItems();
        ArrayList<Usuario> usuarios = conexao.usuarioLista();
        for (Usuario usuario : usuarios) {
            if ("participante".equals(usuario.getTipo())) {
                cmbResponsavel.addItem(usuario);
            }
        }
        cmbResponsavel.setRenderer(FormTarefa.<Usuario>renderer(u -> u.getNome() + "  (" + u.getEmail() + ")"));

        if (cmbProjeto.getItemCount() == 0) {
            lblAlerta.setText("Crie um projeto antes de cadastrar tarefas.");
        } else if (cmbResponsavel.getItemCount() == 0) {
            lblAlerta.setText("Nenhum participante cadastrado para receber tarefas.");
        }
    }

    private void preencher(Tarefa t) {
        txtTitulo.setText(t.getTitulo());
        if (t.getPrazo() != null) {
            spnPrazo.setValue(t.getPrazo());
        }
        PainelFormulario.selecionarValor(cmbStatus, t.getStatus());
        if (t.getProjeto() != null) {
            for (int i = 0; i < cmbProjeto.getItemCount(); i++) {
                if (((Projeto) cmbProjeto.getItemAt(i)).getId() == t.getProjeto().getId()) {
                    cmbProjeto.setSelectedIndex(i);
                    break;
                }
            }
        }
        if (t.getUsuario() != null) {
            for (int i = 0; i < cmbResponsavel.getItemCount(); i++) {
                if (((Usuario) cmbResponsavel.getItemAt(i)).getId() == t.getUsuario().getId()) {
                    cmbResponsavel.setSelectedIndex(i);
                    break;
                }
            }
        }
    }

    private static <T> DefaultListCellRenderer renderer(Function<T, String> texto) {
        return new DefaultListCellRenderer() {
            @Override
            @SuppressWarnings("unchecked")
            public Component getListCellRendererComponent(JList<?> list, Object value, int index,
                    boolean isSelected, boolean cellHasFocus) {
                super.getListCellRendererComponent(list, value, index, isSelected, cellHasFocus);
                setText(value != null ? texto.apply((T) value) : "");
                return this;
            }
        };
    }

    private void salvar() {
        String titulo = txtTitulo.getText().trim();
        Projeto projeto = (Projeto) cmbProjeto.getSelectedItem();
        Usuario responsavel = (Usuario) cmbResponsavel.getSelectedItem();
        if (titulo.isEmpty()) {
            lblAlerta.setText("Informe o título da tarefa.");
            txtTitulo.requestFocus();
            return;
        }
        if (projeto == null) {
            lblAlerta.setText("Selecione um projeto.");
            return;
        }
        if (responsavel == null) {
            lblAlerta.setText("Selecione o colaborador responsável.");
            return;
        }
        Date prazo = (Date) spnPrazo.getValue();
        String status = ((Opcao) cmbStatus.getSelectedItem()).valor();

        boolean ok;
        if (tarefa != null) {
            ok = conexao.tarefaAtualizar(new Tarefa(tarefa.getId(), titulo, prazo, status, projeto,
                    responsavel, tarefa.getCriadoEm()));
        } else {
            ok = conexao.tarefaInserir(new Tarefa(titulo, prazo, status, projeto, responsavel));
        }

        if (ok) {
            JOptionPane.showMessageDialog(this, tarefa != null ? "Tarefa atualizada com sucesso!" : "Tarefa criada com sucesso!");
            dispose();
            if (aoSalvar != null) {
                aoSalvar.run();
            }
        } else {
            lblAlerta.setText("Erro ao salvar a tarefa. Tente novamente.");
        }
    }

