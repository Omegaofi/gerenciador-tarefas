    private void estilizar() {
        PainelTela.estilizarMarca(lblLogo, lblChamada, lblCopyright,
                lblDestaque1, lblDestaque2, lblDestaque3, lblDestaque4);

        Tema.logo(lblLogoPequeno, 16, false);
        Tema.subtitulo(lblPlataforma);
        lblTitulo.setFont(Tema.fonte(Font.BOLD, 17));
        lblAlerta.setFont(Tema.fonte(Font.BOLD, 12));
        Tema.rotuloCampo(lblEmail);
        Tema.rotuloCampo(lblSenha);
        Tema.estilizarCampo(txtEmail);
        Tema.estilizarCampo(txtSenha);
        Tema.primario(btnEntrar).addActionListener(e -> entrar());
        Tema.subtitulo(lblNaoTemConta);
        Tema.link(lnkCadastro).addMouseListener(new MouseAdapter() {
            @Override
            public void mouseClicked(MouseEvent e) {
                TelaCadastro telaCadastro = new TelaCadastro();
                telaCadastro.setBounds(getBounds());
                telaCadastro.setVisible(true);
                dispose();
            }
        });
    }

    private void entrar() {
        String email = txtEmail.getText().trim();
        String senha = new String(txtSenha.getPassword());
        if (email.isEmpty() || senha.isEmpty()) {
            lblAlerta.setText("Informe e-mail e senha.");
            return;
        }

        Usuario userLogado = GerenciadorTarefasCliente.conexaoCliente.usuarioLogin(new Usuario(email, senha));
        if (userLogado != null) {
            GerenciadorTarefasCliente.conexaoCliente.setUsuarioLogado(userLogado);
            TelaPrincipal telaPrincipal = new TelaPrincipal();
            telaPrincipal.setVisible(true);
            dispose();
        } else {
            lblAlerta.setText("E-mail ou senha incorretos.");
            txtSenha.setText("");
            txtSenha.requestFocus();
        }
    }

